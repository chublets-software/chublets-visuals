"""Small helpers that write LaTeX tables for the paper appendix.

The tables are plain `longtable`s with `\\hline` rules, in the style of the
Starter Pack tables (`starter-pack/paper/table-*.tex`): no package beyond
`longtable` and `array`, ASCII only, no timestamp, so a run twice gives the same
bytes. Every number in a caption is passed in by the caller, computed from the
data (PRIMER.md A2).

Font size and column padding are set per table inside a group; a document can
override the size for all of them with
`\\renewcommand{\\chubletstablesize}{\\scriptsize}` in the preamble (the generated
files only `\\providecommand` it).
"""

from __future__ import annotations

import re
from pathlib import Path

HEADER = "% generated by py/step_latex_tables.py ({name}) -- do not edit by hand"

_SPECIAL = {
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
    "\\": r"\textbackslash{}",
    "<": r"$<$",
    ">": r"$>$",
    "|": r"$|$",
}
_REPLACEMENTS = (
    ("<->", r"$\leftrightarrow$"),
    ("\u2192", r"$\rightarrow$"),
    ("\u2248", r"$\approx$"),
    ("\u2013", "--"),
    ("\u2014", "---"),
    ("\u2011", "-"),
    ("\u00e4", r"\"a"),
    ("\u00f6", r"\"o"),
    ("\u00fc", r"\"u"),
    ("\u00e9", r"\'e"),
    ("\u00e3", r"\~a"),
)
_PLACEHOLDER = "\x00"


def esc(text: str) -> str:
    """LaTeX-safe text. Raises on anything it does not know, so a stray character
    is found when the table is written, not when the paper is compiled."""
    out = str(text)
    # protect the multi-character replacements from the single-character pass
    tokens: list[str] = []
    for old, new in _REPLACEMENTS:
        while old in out:
            tokens.append(new)
            out = out.replace(old, f"{_PLACEHOLDER}{len(tokens) - 1}{_PLACEHOLDER}", 1)
    bad = sorted({c for c in out if c != _PLACEHOLDER and (ord(c) > 126 or (ord(c) < 32 and c != "\n") or c in '"`')})
    if bad:
        raise ValueError(f"esc(): cannot write {bad!r} in {text!r}")
    out = "".join(_SPECIAL.get(c, c) for c in out)
    out = re.sub(f"{_PLACEHOLDER}(\\d+){_PLACEHOLDER}", lambda m: tokens[int(m.group(1))], out)
    return out


def breakable(text: str) -> str:
    """esc() plus break points after '/', '.', '-' and camelCase joins, for URLs and
    identifiers in narrow columns."""
    s = esc(text)
    s = re.sub(r"(?<=[/.\-])(?=[A-Za-z0-9])|(?<=[a-z])(?=[A-Z])", r"\\allowbreak{}", s)
    return s


def spec_of(cols) -> str:
    return "".join(pcol(c.width, c.align) if c.width else c.align for c in cols)


def longtable(table, *, size: str = r"\small", tabcolsep: str | None = None) -> str:
    """One complete `longtable` for a tables_data.Table (plain-text cells, escaped here)."""
    from tables_data import Row, Sub  # local: tables_data imports nothing from here

    cols = table.cols
    ncol = len(cols)
    lines = [HEADER.format(name=table.name)]
    lines.append(r"\begingroup")
    lines.append(r"\providecommand{\chubletstablesize}{}")
    lines.append(f"{size}\\chubletstablesize")
    if tabcolsep:
        lines.append(f"\\setlength{{\\tabcolsep}}{{{tabcolsep}}}")
    lines.append(f"\\begin{{longtable}}{{{spec_of(cols)}}}")
    lines.append(f"\\caption{{{esc(table.caption)}}}\\label{{{table.label}}}\\\\")
    head = " & ".join(f"\\textbf{{{esc(c.title)}}}" for c in cols)
    lines.append(r"\hline")
    lines.append(f"{head} \\\\ \\hline")
    lines.append(r"\endfirsthead")
    lines.append(f"\\multicolumn{{{ncol}}}{{l}}{{\\textit{{Table \\thetable{{}} (continued)}}}} \\\\ \\hline")
    lines.append(f"{head} \\\\ \\hline")
    lines.append(r"\endhead")
    lines.append(r"\hline")
    lines.append(r"\endfoot")
    for r in table.rows:
        if isinstance(r, Sub):
            lines.append(f"\\multicolumn{{{ncol}}}{{l}}{{\\textbf{{{esc(r.text)}}}}} \\\\ \\hline")
            continue
        if len(r.cells) != ncol:
            raise ValueError(f"{table.name}: row has {len(r.cells)} cells, header has {ncol}: {r.cells!r}")
        cells = [breakable(c) if col.brk else esc(c) for c, col in zip(r.cells, cols)]
        if r.total:
            cells = [f"\\textbf{{{c}}}" if c else c for c in cells]
        prefix = "\\hline\n" if r.total else ""
        lines.append(prefix + " & ".join(cells) + " \\\\")
    lines.append(r"\end{longtable}")
    lines.append(r"\endgroup")
    return "\n".join(lines) + "\n"


def write(path: Path, text: str) -> None:
    """Write ASCII text with LF endings; refuses anything non-ASCII."""
    text.encode("ascii")  # raises UnicodeEncodeError
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="ascii", newline="\n") as f:
        f.write(text)


def pcol(fraction: float, align: str = "l") -> str:
    """A paragraph column that, padding included, takes `fraction` of the line width
    (ragged right; ragged left for "r")."""
    ragged = "\\raggedleft" if align == "r" else "\\raggedright"
    return ">{" + ragged + "\\arraybackslash}p{\\dimexpr " + f"{fraction:.3f}" + "\\linewidth-2\\tabcolsep\\relax}"
